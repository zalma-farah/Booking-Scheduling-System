-- Private quote, recalculated inside the write transaction, not trusted from UI.
CREATE FUNCTION public.walk_in_window(p_resource_id BIGINT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE
  observed TIMESTAMPTZ := clock_timestamp();
  first_slot public.time_slots;
  following RECORD;
  until_time TIMESTAMPTZ;
  guest_start TIMESTAMPTZ;
  day_end_time TIMESTAMPTZ;
BEGIN
  IF p_resource_id IS NULL OR p_resource_id<1 OR p_resource_id>9007199254740991 THEN
    RAISE EXCEPTION 'Invalid room' USING ERRCODE='22023';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.resources r JOIN public.locations l ON l.id=r.location_id
      WHERE r.id=p_resource_id AND r.is_active AND l.is_active) THEN
    RAISE EXCEPTION 'Room unavailable' USING ERRCODE='P0002';
  END IF;
  SELECT s.* INTO first_slot FROM public.time_slots s
  WHERE s.resource_id=p_resource_id AND s.is_active AND s.start_time<=observed AND s.end_time>observed
    AND NOT EXISTS(SELECT 1 FROM public.bookings b WHERE b.time_slot_id=s.id AND b.status='active');
  IF FOUND AND NOT EXISTS(SELECT 1 FROM public.walk_in_bookings w WHERE w.resource_id=p_resource_id
      AND w.status='active' AND w.start_time<=observed AND w.end_time>observed) THEN
    until_time := first_slot.end_time;
    FOR following IN SELECT s.*, EXISTS(SELECT 1 FROM public.bookings b WHERE b.time_slot_id=s.id AND b.status='active') AS booked
      FROM public.time_slots s WHERE s.resource_id=p_resource_id AND s.start_time>=first_slot.end_time ORDER BY s.start_time
    LOOP
      EXIT WHEN following.start_time<>until_time OR NOT following.is_active OR following.booked;
      until_time := following.end_time;
      EXIT WHEN until_time>=observed+interval '2 hours';
    END LOOP;
    SELECT b.day_end INTO day_end_time FROM public.kiosk_day_bounds(observed) b;
    SELECT min(w.start_time) INTO guest_start FROM public.walk_in_bookings w
      WHERE w.resource_id=p_resource_id AND w.status='active' AND w.start_time>observed;
    until_time := least(until_time,observed+interval '2 hours',day_end_time,guest_start);
    IF until_time<observed+interval '5 minutes' THEN until_time:=NULL; END IF;
  END IF;
  RETURN jsonb_build_object('resource_id',p_resource_id,'checked_at',observed,
    'available_until',until_time,'max_minutes',120,'source_slot_id',first_slot.id);
END $$;

CREATE FUNCTION public.get_walk_in_window(p_resource_id BIGINT)
RETURNS JSONB LANGUAGE sql SECURITY DEFINER SET search_path='' AS $$
  SELECT public.walk_in_window(p_resource_id)-'source_slot_id';
$$;

CREATE FUNCTION public.create_guest_walk_in(p_resource_id BIGINT,p_end_time TIMESTAMPTZ,p_request_id UUID)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE quote JSONB; result public.walk_in_bookings;
BEGIN
  PERFORM pg_catalog.pg_advisory_xact_lock(576,1);
  IF p_request_id IS NULL OR p_end_time IS NULL THEN
    RAISE EXCEPTION 'Invalid confirmation' USING ERRCODE='22023';
  END IF;
  SELECT * INTO result FROM public.walk_in_bookings WHERE request_id=p_request_id;
  IF FOUND THEN
    IF result.resource_id IS DISTINCT FROM p_resource_id OR result.end_time<>p_end_time THEN
      RAISE EXCEPTION 'Confirmation does not match original request' USING ERRCODE='22023';
    END IF;
  ELSE
    quote:=public.walk_in_window(p_resource_id);
    IF (quote->>'available_until') IS NULL OR p_end_time>(quote->>'available_until')::timestamptz
      OR p_end_time<(quote->>'checked_at')::timestamptz+interval '5 minutes' THEN
      RAISE EXCEPTION 'Availability changed. Refresh and choose an available time' USING ERRCODE='23514';
    END IF;
    INSERT INTO public.walk_in_bookings(resource_id,time_slot_id,request_id,start_time,end_time)
      VALUES(p_resource_id,(quote->>'source_slot_id')::bigint,p_request_id,
        (quote->>'checked_at')::timestamptz,p_end_time) RETURNING * INTO result;
  END IF;
  RETURN jsonb_build_object('resource_id',result.resource_id,'start_time',result.start_time,
    'end_time',result.end_time,'status',result.status,'request_id',result.request_id);
END $$;

-- Existing account booking and inventory mutations use the SAME statement lock.
-- Keep the original 004 guards; these additional guards also see guest bookings.
CREATE FUNCTION public.guard_walk_in_conflicts()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
  IF TG_TABLE_NAME='bookings' THEN
    IF NEW.status='active' AND EXISTS(SELECT 1 FROM public.walk_in_bookings w JOIN public.time_slots s
      ON s.resource_id=w.resource_id WHERE s.id=NEW.time_slot_id AND w.status='active'
      AND w.start_time<s.end_time AND w.end_time>s.start_time) THEN
      RAISE EXCEPTION 'Slot overlaps a walk-in reservation' USING ERRCODE='23514';
    END IF;
  ELSIF TG_TABLE_NAME='resources' THEN
    IF NOT NEW.is_active AND EXISTS(SELECT 1 FROM public.walk_in_bookings w
      WHERE w.resource_id=OLD.id AND w.status='active' AND w.end_time>clock_timestamp()) THEN
      RAISE EXCEPTION 'Cancel walk-in reservations before archiving' USING ERRCODE='23514';
    END IF;
  ELSIF TG_TABLE_NAME='locations' THEN
    IF NOT NEW.is_active AND EXISTS(SELECT 1 FROM public.walk_in_bookings w JOIN public.resources r ON r.id=w.resource_id
      WHERE r.location_id=OLD.id AND w.status='active' AND w.end_time>clock_timestamp()) THEN
      RAISE EXCEPTION 'Cancel walk-in reservations before archiving' USING ERRCODE='23514';
    END IF;
  ELSIF NOT NEW.is_active AND EXISTS(SELECT 1 FROM public.walk_in_bookings w WHERE w.resource_id=OLD.resource_id
    AND w.status='active' AND w.end_time>clock_timestamp() AND w.start_time<OLD.end_time AND w.end_time>OLD.start_time) THEN
    RAISE EXCEPTION 'Cancel walk-in reservations before disabling slot' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER guard_walk_in_booking BEFORE INSERT OR UPDATE ON public.bookings FOR EACH ROW EXECUTE FUNCTION public.guard_walk_in_conflicts();
CREATE TRIGGER guard_walk_in_resource BEFORE UPDATE ON public.resources FOR EACH ROW EXECUTE FUNCTION public.guard_walk_in_conflicts();
CREATE TRIGGER guard_walk_in_location BEFORE UPDATE ON public.locations FOR EACH ROW EXECUTE FUNCTION public.guard_walk_in_conflicts();
CREATE TRIGGER guard_walk_in_slot BEFORE UPDATE ON public.time_slots FOR EACH ROW EXECUTE FUNCTION public.guard_walk_in_conflicts();

-- Segment each enabled slot around guest intervals so the display stays truthful.
CREATE FUNCTION public.walk_in_kiosk_snapshot(p_resource_id BIGINT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE observed TIMESTAMPTZ:=clock_timestamp(); first_time TIMESTAMPTZ; last_time TIMESTAMPTZ; result JSONB;
BEGIN
  IF p_resource_id IS NULL OR p_resource_id<1 THEN RAISE EXCEPTION 'Invalid room' USING ERRCODE='22023'; END IF;
  SELECT b.day_start,b.day_end INTO first_time,last_time FROM public.kiosk_day_bounds(observed) b;
  SELECT jsonb_build_object('timezone','America/Los_Angeles','checked_at',observed,
    'day_start',first_time,'day_end',last_time,'resource',jsonb_build_object('id',r.id,'name',r.name,
      'location',jsonb_build_object('id',l.id,'name',l.name)),
    'slots',coalesce((
      WITH enabled AS (
        SELECT s.*,EXISTS(SELECT 1 FROM public.bookings b WHERE b.time_slot_id=s.id AND b.status='active') AS booked
        FROM public.time_slots s WHERE s.resource_id=r.id AND s.is_active AND s.start_time<last_time AND s.end_time>first_time
      ), boundaries AS (
        SELECT e.id,e.booked,e.start_time AS t FROM enabled e UNION
        SELECT e.id,e.booked,e.end_time FROM enabled e UNION
        SELECT e.id,e.booked,greatest(e.start_time,w.start_time) FROM enabled e JOIN public.walk_in_bookings w
          ON w.resource_id=e.resource_id AND w.status='active' AND w.start_time<e.end_time AND w.end_time>e.start_time UNION
        SELECT e.id,e.booked,least(e.end_time,w.end_time) FROM enabled e JOIN public.walk_in_bookings w
          ON w.resource_id=e.resource_id AND w.status='active' AND w.start_time<e.end_time AND w.end_time>e.start_time
      ), segments AS (SELECT id,booked,t AS start_time,lead(t) OVER(PARTITION BY id ORDER BY t) AS end_time FROM boundaries),
      numbered AS (SELECT row_number() OVER(ORDER BY s.start_time,s.id) AS id,s.start_time,s.end_time,
        s.booked OR EXISTS(SELECT 1 FROM public.walk_in_bookings w WHERE w.resource_id=r.id AND w.status='active'
          AND w.start_time<s.end_time AND w.end_time>s.start_time) AS is_booked
        FROM segments s WHERE s.end_time>s.start_time AND s.start_time<last_time AND s.end_time>first_time
        ORDER BY s.start_time,s.id LIMIT 501)
      SELECT jsonb_agg(jsonb_build_object('id',n.id,'start_time',n.start_time,'end_time',n.end_time,'is_booked',n.is_booked)
        ORDER BY n.start_time,n.id) FROM numbered n
    ),'[]'::jsonb)) INTO result
    FROM public.resources r JOIN public.locations l ON l.id=r.location_id
    WHERE r.id=p_resource_id AND r.is_active AND l.is_active;
  IF result IS NULL THEN RAISE EXCEPTION 'Room unavailable' USING ERRCODE='P0002'; END IF;
  RETURN result;
END $$;
CREATE OR REPLACE FUNCTION public.get_public_room_kiosk_status(p_resource_id BIGINT)
RETURNS JSONB LANGUAGE sql SECURITY DEFINER SET search_path='' AS $$
  SELECT public.walk_in_kiosk_snapshot(p_resource_id);
$$;
