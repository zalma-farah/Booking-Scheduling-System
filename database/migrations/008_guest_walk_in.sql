CREATE TABLE public.walk_in_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id BIGINT NOT NULL REFERENCES public.resources(id) ON DELETE RESTRICT,
  time_slot_id BIGINT NOT NULL REFERENCES public.time_slots(id) ON DELETE RESTRICT,
  request_id UUID NOT NULL UNIQUE,
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  cancelled_at TIMESTAMPTZ,
  CHECK(end_time > start_time AND end_time <= start_time + interval '2 hours'),
  CHECK((status='active' AND cancelled_at IS NULL) OR (status='cancelled' AND cancelled_at IS NOT NULL)),
  EXCLUDE USING gist(resource_id WITH =, tstzrange(start_time,end_time,'[)') WITH &&) WHERE(status='active')
);
