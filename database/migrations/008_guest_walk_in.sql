CREATE OR REPLACE FUNCTION public.get_resource_availability(p_resource_id BIGINT)
RETURNS TABLE(id BIGINT,start_time TIMESTAMPTZ,end_time TIMESTAMPTZ,is_available BOOLEAN)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
BEGIN
  IF NOT public.is_active_account() THEN RAISE EXCEPTION 'Active account required' USING ERRCODE='42501'; END IF;
  IF p_resource_id IS NULL OR p_resource_id<1 THEN RAISE EXCEPTION 'Invalid room' USING ERRCODE='22023'; END IF;
  RETURN QUERY SELECT s.id,s.start_time,s.end_time,
    NOT EXISTS(SELECT 1 FROM public.bookings b WHERE b.time_slot_id=s.id AND b.status='active')
    AND NOT EXISTS(SELECT 1 FROM public.walk_in_bookings w WHERE w.resource_id=s.resource_id AND w.status='active'
      AND w.start_time<s.end_time AND w.end_time>s.start_time)
    FROM public.time_slots s JOIN public.resources r ON r.id=s.resource_id JOIN public.locations l ON l.id=r.location_id
    WHERE r.id=p_resource_id AND r.is_active AND l.is_active AND s.is_active
      AND s.start_time>now() AND s.start_time<now()+interval '30 days'
    ORDER BY s.start_time,s.id LIMIT 100;
END $$;

CREATE FUNCTION public.list_walk_in_rooms(p_after BIGINT DEFAULT 0)
RETURNS JSONB LANGUAGE sql SECURITY DEFINER SET search_path='' AS $$
  WITH page AS (SELECT r.id,r.name,jsonb_build_object('id',l.id,'name',l.name) AS location
    FROM public.resources r JOIN public.locations l ON l.id=r.location_id
    WHERE r.is_active AND l.is_active AND r.id>greatest(coalesce(p_after,0),0) ORDER BY r.id LIMIT 51),
  visible AS (SELECT * FROM page ORDER BY id LIMIT 50)
  SELECT jsonb_build_object('rooms',coalesce((SELECT jsonb_agg(to_jsonb(v) ORDER BY v.id) FROM visible v),'[]'::jsonb),
    'next_after',CASE WHEN (SELECT count(*) FROM page)>50 THEN (SELECT max(id) FROM visible) ELSE NULL END);
$$;

CREATE FUNCTION public.list_managed_walk_ins(p_status TEXT DEFAULT 'all')
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE result JSONB;
BEGIN
  IF NOT public.is_active_account() OR NOT EXISTS(SELECT 1 FROM public.get_admin_organization()) THEN
    RAISE EXCEPTION 'Assigned active administrator required' USING ERRCODE='42501';
  END IF;
  IF p_status IS NULL OR p_status NOT IN ('all','active','cancelled') THEN RAISE EXCEPTION 'Invalid status' USING ERRCODE='22023'; END IF;
  SELECT coalesce(jsonb_agg(row_data ORDER BY created_at DESC,id DESC),'[]'::jsonb) INTO result FROM (
    SELECT w.id,w.created_at,jsonb_build_object('id',w.id,'kind','walk_in','status',w.status,
      'created_at',w.created_at,'slot',jsonb_build_object('start_time',w.start_time,'end_time',w.end_time,
        'resource',jsonb_build_object('id',r.id,'name',r.name,'location',jsonb_build_object('name',l.name)))) AS row_data
    FROM public.walk_in_bookings w JOIN public.resources r ON r.id=w.resource_id JOIN public.locations l ON l.id=r.location_id
    WHERE public.can_manage_resource(w.resource_id) AND (p_status='all' OR w.status=p_status)
    ORDER BY w.created_at DESC,w.id DESC LIMIT 100
  ) recent;
  RETURN result;
END $$;
CREATE FUNCTION public.managed_guest_blocked_slots(p_slot_ids BIGINT[])
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
  IF NOT public.is_active_account() OR NOT EXISTS(SELECT 1 FROM public.get_admin_organization()) THEN
    RAISE EXCEPTION 'Assigned active administrator required' USING ERRCODE='42501';
  END IF;
  IF p_slot_ids IS NULL OR cardinality(p_slot_ids)>100 THEN RAISE EXCEPTION 'Invalid slot list' USING ERRCODE='22023'; END IF;
  RETURN (SELECT coalesce(jsonb_agg(s.id),'[]'::jsonb) FROM public.time_slots s
    WHERE s.id=ANY(p_slot_ids) AND public.can_manage_resource(s.resource_id)
      AND EXISTS(SELECT 1 FROM public.walk_in_bookings w WHERE w.resource_id=s.resource_id AND w.status='active'
        AND w.start_time<s.end_time AND w.end_time>s.start_time));
END $$;

CREATE FUNCTION public.cancel_managed_walk_in(p_booking_id BIGINT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE result public.walk_in_bookings;
BEGIN
  PERFORM pg_catalog.pg_advisory_xact_lock(576,1);
  SELECT * INTO result FROM public.walk_in_bookings w WHERE w.id=p_booking_id AND public.can_manage_resource(w.resource_id);
  IF NOT FOUND THEN RAISE EXCEPTION 'Reservation not found or not managed' USING ERRCODE='42501'; END IF;
  UPDATE public.walk_in_bookings w SET status='cancelled',cancelled_at=clock_timestamp()
    WHERE w.id=p_booking_id AND w.status='active' RETURNING w.* INTO result;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reservation already cancelled' USING ERRCODE='23514'; END IF;
  RETURN jsonb_build_object('id',result.id,'kind','walk_in','status',result.status);
END $$;

