BEGIN;

-- Stop if the live project contains additional policies that this migration
-- has not reviewed. A leftover permissive policy could preserve global access.
DO $preflight$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_catalog.pg_policies AS policy
        WHERE policy.schemaname = 'public'
          AND policy.tablename IN ('profiles', 'locations', 'resources', 'time_slots', 'bookings')
          AND NOT EXISTS (
              SELECT 1 FROM (VALUES
                  ('profiles', 'Users can view own profile'),
                  ('profiles', 'Administrators can update profiles'),
                  ('locations', 'Users can view active locations'),
                  ('locations', 'Administrators can create locations'),
                  ('locations', 'Administrators can update locations'),
                  ('locations', 'Administrators can delete locations'),
                  ('resources', 'Users can view active resources'),
                  ('resources', 'Administrators can create resources'),
                  ('resources', 'Administrators can update resources'),
                  ('resources', 'Administrators can delete resources'),
                  ('time_slots', 'Users can view active time slots'),
                  ('time_slots', 'Administrators can create time slots'),
                  ('time_slots', 'Administrators can update time slots'),
                  ('time_slots', 'Administrators can delete time slots'),
                  ('bookings', 'Users can view own bookings'),
                  ('bookings', 'Users can create valid bookings'),
                  ('bookings', 'Administrators can update bookings')
              ) AS expected(table_name, policy_name)
              WHERE expected.table_name = policy.tablename
                AND expected.policy_name = policy.policyname
          )
    ) THEN
        RAISE EXCEPTION 'Additional live RLS policies found. Stop and review pg_policies before applying organization access.';
    END IF;

    IF EXISTS (
        SELECT 1 FROM pg_catalog.pg_class AS relation
        JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation.relnamespace
        WHERE namespace.nspname = 'public'
          AND relation.relname IN ('profiles', 'locations', 'resources', 'time_slots', 'bookings')
          AND relation.relrowsecurity = FALSE
    ) THEN
        RAISE EXCEPTION 'RLS is disabled on an application table. Stop and review before applying organization access.';
    END IF;
END;
$preflight$;

CREATE TABLE public.organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_-]{1,29}$'),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- One university per administrator; several administrators may manage a university.
-- Membership alone is insufficient: the profile must also be active and administrator.
CREATE TABLE public.organization_admins (
    user_id UUID PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.organizations (code, name)
VALUES ('SDSU', 'San Diego State University'),
       ('UCSD', 'University of California San Diego');

ALTER TABLE public.locations
ADD COLUMN organization_id BIGINT REFERENCES public.organizations(id) ON DELETE RESTRICT;

UPDATE public.locations
SET organization_id = (SELECT id FROM public.organizations WHERE code = 'SDSU');

ALTER TABLE public.locations ALTER COLUMN organization_id SET NOT NULL;

CREATE INDEX locations_organization_id_idx ON public.locations(organization_id);
CREATE INDEX organization_admins_organization_id_idx ON public.organization_admins(organization_id);
CREATE INDEX IF NOT EXISTS resources_location_id_idx ON public.resources(location_id);
CREATE INDEX IF NOT EXISTS time_slots_resource_id_idx ON public.time_slots(resource_id);
CREATE INDEX IF NOT EXISTS bookings_user_id_idx ON public.bookings(user_id);

ALTER TABLE public.organizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.organization_admins ENABLE ROW LEVEL SECURITY;

CREATE FUNCTION public.is_active_account()
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles AS profile
        WHERE profile.id = auth.uid() AND profile.is_active = TRUE
    );
$$;

-- The caller is always auth.uid(). No caller-supplied user ID or email is trusted.
CREATE FUNCTION public.can_manage_organization(p_organization_id BIGINT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.organization_admins AS assignment
        JOIN public.profiles AS profile ON profile.id = assignment.user_id
        WHERE assignment.user_id = auth.uid()
          AND assignment.organization_id = p_organization_id
          AND assignment.is_active = TRUE
          AND profile.role = 'administrator'
          AND profile.is_active = TRUE
    );
$$;

CREATE FUNCTION public.current_admin_organization_id()
RETURNS BIGINT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT assignment.organization_id
    FROM public.organization_admins AS assignment
    JOIN public.profiles AS profile ON profile.id = assignment.user_id
    WHERE assignment.user_id = auth.uid()
      AND assignment.is_active = TRUE
      AND profile.role = 'administrator'
      AND profile.is_active = TRUE;
$$;

CREATE FUNCTION public.get_admin_organization()
RETURNS TABLE (id BIGINT, code TEXT, name TEXT)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT organization.id, organization.code, organization.name
    FROM public.organizations AS organization
    WHERE organization.id = public.current_admin_organization_id();
$$;

CREATE FUNCTION public.can_manage_location(p_location_id BIGINT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.locations AS location
        WHERE location.id = p_location_id
          AND public.can_manage_organization(location.organization_id)
    );
$$;

CREATE FUNCTION public.can_manage_resource(p_resource_id BIGINT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.resources AS resource
        WHERE resource.id = p_resource_id
          AND public.can_manage_location(resource.location_id)
    );
$$;

CREATE FUNCTION public.can_manage_slot(p_time_slot_id BIGINT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.time_slots AS slot
        WHERE slot.id = p_time_slot_id
          AND public.can_manage_resource(slot.resource_id)
    );
$$;

REVOKE ALL ON FUNCTION public.is_active_account() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.can_manage_organization(BIGINT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.current_admin_organization_id() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.get_admin_organization() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.can_manage_location(BIGINT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.can_manage_resource(BIGINT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.can_manage_slot(BIGINT) FROM PUBLIC, anon, authenticated;

