GRANT EXECUTE ON FUNCTION public.current_admin_organization_id() TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_admin_organization() TO authenticated;
GRANT EXECUTE ON FUNCTION public.can_manage_location(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.can_manage_resource(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.can_manage_slot(BIGINT) TO authenticated;

-- The old application can still create a location without sending organization_id.
-- The default comes from the verified account's assignment, never from its email.
ALTER TABLE public.locations
ALTER COLUMN organization_id SET DEFAULT public.current_admin_organization_id();

-- REPLACE the existing global policies; adding permissive policies would not narrow them.
DROP POLICY "Users can view own profile" ON public.profiles;
DROP POLICY "Administrators can update profiles" ON public.profiles;

CREATE POLICY "Accounts can read own profile" ON public.profiles
FOR SELECT TO authenticated USING (id = (SELECT auth.uid()));

CREATE POLICY "Active accounts can read organization names" ON public.organizations
FOR SELECT TO authenticated USING ((SELECT public.is_active_account()));

CREATE POLICY "Administrators can read own assignment" ON public.organization_admins
FOR SELECT TO authenticated USING (
    user_id = (SELECT auth.uid()) AND (SELECT public.is_active_account())
);

DROP POLICY "Users can view active locations" ON public.locations;
DROP POLICY "Administrators can create locations" ON public.locations;
DROP POLICY "Administrators can update locations" ON public.locations;
DROP POLICY "Administrators can delete locations" ON public.locations;

CREATE POLICY "Accounts can browse locations" ON public.locations
FOR SELECT TO authenticated USING (
    (is_active = TRUE AND (SELECT public.is_active_account()))
    OR public.can_manage_organization(organization_id)
);
CREATE POLICY "Assigned administrators can create locations" ON public.locations
FOR INSERT TO authenticated WITH CHECK (public.can_manage_organization(organization_id));
CREATE POLICY "Assigned administrators can update locations" ON public.locations
FOR UPDATE TO authenticated
USING (public.can_manage_organization(organization_id))
WITH CHECK (public.can_manage_organization(organization_id));

DROP POLICY "Users can view active resources" ON public.resources;
DROP POLICY "Administrators can create resources" ON public.resources;
DROP POLICY "Administrators can update resources" ON public.resources;
DROP POLICY "Administrators can delete resources" ON public.resources;

CREATE POLICY "Accounts can browse resources" ON public.resources
FOR SELECT TO authenticated USING (
    (is_active = TRUE AND (SELECT public.is_active_account()) AND EXISTS (
        SELECT 1 FROM public.locations AS location
        WHERE location.id = resources.location_id AND location.is_active = TRUE
    ))
    OR public.can_manage_location(location_id)
);
CREATE POLICY "Assigned administrators can create resources" ON public.resources
FOR INSERT TO authenticated WITH CHECK (public.can_manage_location(location_id));
CREATE POLICY "Assigned administrators can update resources" ON public.resources
FOR UPDATE TO authenticated
USING (public.can_manage_location(location_id))
WITH CHECK (public.can_manage_location(location_id));

DROP POLICY "Users can view active time slots" ON public.time_slots;
DROP POLICY "Administrators can create time slots" ON public.time_slots;
DROP POLICY "Administrators can update time slots" ON public.time_slots;
DROP POLICY "Administrators can delete time slots" ON public.time_slots;

CREATE POLICY "Accounts can browse time slots" ON public.time_slots
FOR SELECT TO authenticated USING (
    (is_active = TRUE AND (SELECT public.is_active_account()) AND EXISTS (
        SELECT 1 FROM public.resources AS resource
        JOIN public.locations AS location ON location.id = resource.location_id
        WHERE resource.id = time_slots.resource_id
          AND resource.is_active = TRUE AND location.is_active = TRUE
    ))
    OR public.can_manage_resource(resource_id)
);
CREATE POLICY "Assigned administrators can create time slots" ON public.time_slots
FOR INSERT TO authenticated WITH CHECK (public.can_manage_resource(resource_id));
CREATE POLICY "Assigned administrators can update time slots" ON public.time_slots
FOR UPDATE TO authenticated
USING (public.can_manage_resource(resource_id))
WITH CHECK (public.can_manage_resource(resource_id));

DROP POLICY "Users can view own bookings" ON public.bookings;
DROP POLICY "Administrators can update bookings" ON public.bookings;

CREATE POLICY "Accounts can read own or managed bookings" ON public.bookings
FOR SELECT TO authenticated USING (
    (user_id = (SELECT auth.uid()) AND (SELECT public.is_active_account()))
    OR public.can_manage_slot(time_slot_id)
);
CREATE POLICY "Assigned administrators can update bookings" ON public.bookings
FOR UPDATE TO authenticated
USING (public.can_manage_slot(time_slot_id))
WITH CHECK (public.can_manage_slot(time_slot_id));

-- Keep migration 002's future-booking policy and owner-only cancellation RPC intact.
-- Ordinary users may still browse/book active resources across universities.

-- Normalize grants as well as policies: RLS does not protect TRUNCATE.
-- No browser account can create organizations, change roles, or assign universities.
REVOKE ALL ON TABLE public.organizations, public.organization_admins, public.profiles
FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.organizations, public.organization_admins, public.profiles
TO authenticated;

REVOKE ALL ON TABLE public.locations, public.resources, public.time_slots, public.bookings
FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.locations, public.resources, public.time_slots, public.bookings TO authenticated;
GRANT UPDATE (name, address, is_active) ON public.locations TO authenticated;
GRANT UPDATE (name, description, is_active) ON public.resources TO authenticated;
GRANT UPDATE (is_active) ON public.time_slots TO authenticated;

REVOKE ALL ON SEQUENCE public.organizations_id_seq FROM PUBLIC, anon, authenticated;

NOTIFY pgrst, 'reload schema';
COMMIT;
