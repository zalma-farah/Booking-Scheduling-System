-- ============================================================
-- 14. BOOKING SECURITY POLICIES
-- ============================================================

-- Regular users can view only their own bookings.
-- Administrators can view all bookings.

CREATE POLICY "Users can view own bookings"
ON public.bookings
FOR SELECT
TO authenticated
USING (
    user_id = auth.uid()
    OR public.is_admin()
);


-- Regular users can create bookings only for themselves.
-- New reservations must have active status.

CREATE POLICY "Users can create own bookings"
ON public.bookings
FOR INSERT
TO authenticated
WITH CHECK (
    user_id = auth.uid()
    AND status = 'active'
);


-- Administrators can update any booking.

CREATE POLICY "Administrators can update bookings"
ON public.bookings
FOR UPDATE
TO authenticated
USING (
    public.is_admin()
)
WITH CHECK (
    public.is_admin()
);


-- Only administrators can permanently delete bookings.
-- Regular cancellation preserves the booking record.

CREATE POLICY "Administrators can delete bookings"
ON public.bookings
FOR DELETE
TO authenticated
USING (
    public.is_admin()
);


-- ============================================================
-- 15. SECURE USER CANCELLATION
--
-- Regular users do not receive general UPDATE permission on
-- their bookings.
--
-- Instead, they call this function. It only allows the
-- currently authenticated user to cancel their own active
-- reservation.
-- ============================================================

CREATE OR REPLACE FUNCTION public.cancel_own_booking(
    booking_id BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN

    UPDATE public.bookings
    SET
        status = 'cancelled',
        cancelled_at = NOW()
    WHERE id = booking_id
      AND user_id = auth.uid()
      AND status = 'active';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Booking not found, already cancelled, or does not belong to user';
    END IF;

END;
$$;


-- Do not allow anonymous/public callers to execute the
-- cancellation function.

REVOKE ALL
ON FUNCTION public.cancel_own_booking(BIGINT)
FROM PUBLIC;


-- Authenticated users may execute the function.
-- Ownership is still checked inside the function.

GRANT EXECUTE
ON FUNCTION public.cancel_own_booking(BIGINT)
TO authenticated;


