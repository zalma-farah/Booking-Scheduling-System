-- ============================================================
-- 8. AUTOMATIC PROFILE CREATION
--
-- Supabase Authentication stores login accounts in auth.users.
--
-- Whenever a new authentication account is created, this
-- function automatically creates the corresponding application
-- profile.
--
-- All new accounts begin with the regular "user" role.
-- ============================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN

    INSERT INTO public.profiles (
        id,
        email,
        role
    )
    VALUES (
        NEW.id,
        NEW.email,
        'user'
    );

    RETURN NEW;

END;
$$;


CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();


-- ============================================================
-- 9. ADMINISTRATOR ROLE CHECK
--
-- Returns true when the currently authenticated user has the
-- administrator role.
-- ============================================================

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = auth.uid()
          AND role = 'administrator'
    );
$$;


-- ============================================================
-- 10. PROFILE SECURITY POLICIES
-- ============================================================

-- Regular users can view their own profile.
-- Administrators can view all profiles.

CREATE POLICY "Users can view own profile"
ON public.profiles
FOR SELECT
TO authenticated
USING (
    id = auth.uid()
    OR public.is_admin()
);


-- Only administrators can update profiles.
-- This allows administrators to manage user roles.

CREATE POLICY "Administrators can update profiles"
ON public.profiles
FOR UPDATE
TO authenticated
USING (
    public.is_admin()
)
WITH CHECK (
    public.is_admin()
);


