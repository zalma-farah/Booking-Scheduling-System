-- ============================================================
-- 8. AUTOMATIC PROFILE CREATION
--
-- When Supabase Auth creates a user, this function creates the
-- corresponding public profile.
--
-- Every new user begins with the regular "user" role.
-- ============================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (
        id,
        email,
        role,
        is_active
    )
    VALUES (
        NEW.id,
        NEW.email,
        'user',
        TRUE
    );

    RETURN NEW;
END;
$$;


CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();


-- The trigger function should not be called directly by users.

REVOKE ALL
ON FUNCTION public.handle_new_user()
FROM PUBLIC;

REVOKE ALL
ON FUNCTION public.handle_new_user()
FROM anon;

REVOKE ALL
ON FUNCTION public.handle_new_user()
FROM authenticated;


-- ============================================================
-- 9. ADMINISTRATOR ROLE CHECK
--
-- Returns TRUE when the currently authenticated user is an
-- active administrator.
-- ============================================================

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = auth.uid()
          AND role = 'administrator'
          AND is_active = TRUE
    );
$$;


REVOKE ALL
ON FUNCTION public.is_admin()
FROM PUBLIC;

REVOKE ALL
ON FUNCTION public.is_admin()
FROM anon;

GRANT EXECUTE
ON FUNCTION public.is_admin()
TO authenticated;


