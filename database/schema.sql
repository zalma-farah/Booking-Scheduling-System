-- ============================================================
-- BOOKING AND SCHEDULING SYSTEM
-- Database and Authentication Schema
-- ============================================================


-- ============================================================
-- 1. PROFILES
-- Stores application information for Supabase Auth users.
-- Every authenticated user has a matching profile.
-- ============================================================

CREATE TABLE public.profiles (
    id UUID PRIMARY KEY
        REFERENCES auth.users(id) ON DELETE CASCADE,

    email TEXT NOT NULL,

    role TEXT NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'administrator')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 2. LOCATIONS
-- Stores locations containing bookable resources.
-- ============================================================

CREATE TABLE public.locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name TEXT NOT NULL,

    address TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 3. RESOURCES
-- Resources belong to locations.
-- ============================================================

CREATE TABLE public.resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    location_id BIGINT NOT NULL
        REFERENCES public.locations(id) ON DELETE CASCADE,

    name TEXT NOT NULL,

    description TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 4. TIME SLOTS
-- Stores available reservation periods for resources.
-- ============================================================

CREATE TABLE public.time_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    resource_id BIGINT NOT NULL
        REFERENCES public.resources(id) ON DELETE CASCADE,

    start_time TIMESTAMPTZ NOT NULL,

    end_time TIMESTAMPTZ NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT valid_time_slot
        CHECK (end_time > start_time)
);


-- Prevent the exact same time slot from being created twice
-- for the same resource.

CREATE UNIQUE INDEX unique_resource_time_slot
ON public.time_slots (
    resource_id,
    start_time,
    end_time
);


-- ============================================================
-- 5. BOOKINGS
-- Connects users to reserved time slots.
--
-- active     = currently reserved
-- cancelled  = reservation was cancelled
-- ============================================================

CREATE TABLE public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,

    time_slot_id BIGINT NOT NULL
        REFERENCES public.time_slots(id) ON DELETE CASCADE,

    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'cancelled')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    cancelled_at TIMESTAMPTZ
);


-- ============================================================
-- 6. PREVENT DOUBLE BOOKING
--
-- Only one ACTIVE booking may exist for a time slot.
--
-- Cancelled bookings remain in the database for history but
-- do not prevent the slot from being booked again.
-- ============================================================

CREATE UNIQUE INDEX one_active_booking_per_slot
ON public.bookings(time_slot_id)
WHERE status = 'active';


