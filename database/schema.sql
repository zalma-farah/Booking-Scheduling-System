-- ============================================================
-- 1. REQUIRED EXTENSIONS
--
-- btree_gist allows PostgreSQL to prevent overlapping time
-- periods for the same resource.
-- ============================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;


-- ============================================================
-- 2. PROFILES
--
-- Stores application information for Supabase Auth users.
-- Every authenticated user has a matching profile.
-- ============================================================

CREATE TABLE public.profiles (
    id UUID PRIMARY KEY
        REFERENCES auth.users(id) ON DELETE CASCADE,

    email TEXT NOT NULL,

    role TEXT NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'administrator')),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 3. LOCATIONS
-- ============================================================

CREATE TABLE public.locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name TEXT NOT NULL,

    address TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 4. RESOURCES
--
-- ON DELETE RESTRICT prevents a location from being deleted
-- while it still contains resources.
-- ============================================================

CREATE TABLE public.resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    location_id BIGINT NOT NULL
        REFERENCES public.locations(id) ON DELETE RESTRICT,

    name TEXT NOT NULL,

    description TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 5. TIME SLOTS
--
-- ON DELETE RESTRICT protects time-slot history.
-- ============================================================

CREATE TABLE public.time_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    resource_id BIGINT NOT NULL
        REFERENCES public.resources(id) ON DELETE RESTRICT,

    start_time TIMESTAMPTZ NOT NULL,

    end_time TIMESTAMPTZ NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT valid_time_slot
        CHECK (end_time > start_time)
);


-- Prevent overlapping time slots for the same resource.
--
-- [) means the start is included and the end is excluded.
-- Therefore, 9:00–10:00 and 10:00–11:00 are allowed.

ALTER TABLE public.time_slots
ADD CONSTRAINT prevent_overlapping_time_slots
EXCLUDE USING gist (
    resource_id WITH =,
    tstzrange(start_time, end_time, '[)') WITH &&
);


-- ============================================================
-- 6. BOOKINGS
--
-- If a user is deleted, user_id becomes NULL while the booking
-- remains for historical records.
--
-- A time slot cannot be deleted if it has booking history.
-- ============================================================

CREATE TABLE public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID
        REFERENCES public.profiles(id) ON DELETE SET NULL,

    time_slot_id BIGINT NOT NULL
        REFERENCES public.time_slots(id) ON DELETE RESTRICT,

    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'cancelled')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    cancelled_at TIMESTAMPTZ,

    CONSTRAINT valid_booking_cancellation
        CHECK (
            (
                status = 'active'
                AND cancelled_at IS NULL
            )
            OR
            (
                status = 'cancelled'
                AND cancelled_at IS NOT NULL
            )
        )
);


-- Only one active booking may exist for a time slot.
--
-- PostgreSQL enforces this even if two users attempt to book
-- the same slot at almost exactly the same time.

CREATE UNIQUE INDEX one_active_booking_per_slot
ON public.bookings(time_slot_id)
WHERE status = 'active';


