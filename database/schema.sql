-- 10. PROFILE SECURITY POLICIES
-- ============================================================

-- Users can view their own profile.
-- Administrators can view every profile.

CREATE POLICY "Users can view own profile"
ON public.profiles
FOR SELECT
TO authenticated
USING (
    id = auth.uid()
    OR public.is_admin()
);


-- Only administrators can update profiles and roles.

CREATE POLICY "Administrators can update profiles"
ON public.profiles
FOR UPDATE
TO authenticated
USING (
    public.is_admin()
)
WITH CHECK (
    public.is_admin()
);


