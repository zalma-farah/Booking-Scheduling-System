-- ============================================================
-- 14. BOOKING SECURITY POLICIES
-- ============================================================

-- Users can view their own bookings.
-- Administrators can view all bookings.
--
-- If a deleted user has historical bookings, user_id will be
-- NULL and only an administrator can view those records.

CREATE POLICY "Users can view own bookings"
ON public.bookings
FOR SELECT
TO authenticated
USING (
    user_id = auth.uid()
    OR public.is_admin()
);


-- Users may create bookings only:
--
-- 1. For themselves
-- 2. With active status
-- 3. While their profile is active
-- 4. For an active time slot
-- 5. For an active resource and location

CREATE POLICY "Users can create valid bookings"
ON public.bookings
FOR INSERT
TO authenticated
WITH CHECK (
    user_id = auth.uid()

    AND status = 'active'

    AND cancelled_at IS NULL

    AND EXISTS (
        SELECT 1
        FROM public.profiles AS profile
        WHERE profile.id = auth.uid()
          AND profile.is_active = TRUE
    )

    AND EXISTS (
        SELECT 1
        FROM public.time_slots AS slot
        INNER JOIN public.resources AS resource
            ON resource.id = slot.resource_id
        INNER JOIN public.locations AS location
            ON location.id = resource.location_id
        WHERE slot.id = time_slot_id
          AND slot.is_active = TRUE
          AND resource.is_active = TRUE
          AND location.is_active = TRUE
    )
);


-- Administrators can update bookings.
--
-- The valid_booking_cancellation constraint ensures status and
-- cancelled_at remain consistent.

CREATE POLICY "Administrators can update bookings"
ON public.bookings
FOR UPDATE
TO authenticated
USING (
    public.is_admin()
)
WITH CHECK (
    public.is_admin()
);


-- There is intentionally no DELETE policy for bookings.
-- Booking history should be preserved.
-- Administrators cancel bookings instead of deleting them.


-- ============================================================
-- 15. SECURE USER CANCELLATION
--
-- Users do not receive general UPDATE access to bookings.
-- They use this controlled function to cancel their own active
-- booking.
-- ============================================================

CREATE OR REPLACE FUNCTION public.cancel_own_booking(
    booking_id BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    UPDATE public.bookings
    SET
        status = 'cancelled',
        cancelled_at = NOW()
    WHERE id = booking_id
      AND user_id = auth.uid()
      AND status = 'active';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Booking not found, already cancelled, or does not belong to user';
    END IF;
END;
$$;


-- Remove default execution permissions before granting access
-- only to authenticated users.

REVOKE ALL
ON FUNCTION public.cancel_own_booking(BIGINT)
FROM PUBLIC;

REVOKE ALL
ON FUNCTION public.cancel_own_booking(BIGINT)
FROM anon;

REVOKE ALL
ON FUNCTION public.cancel_own_booking(BIGINT)
FROM authenticated;

GRANT EXECUTE
ON FUNCTION public.cancel_own_booking(BIGINT)
TO authenticated;


